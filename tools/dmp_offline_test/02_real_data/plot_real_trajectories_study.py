#!/usr/bin/env python3
"""Comparative plots for analyzing real trajectories (Traj A, B, C)
comparing regression methods in REGRESSION_VARIANTS (e.g., LWR vs Ridge).

Reads the summary CSV generated by run_real_trajectories_sweep.sh and produces:
  1. Grouped bar charts (Trajectory A, B, C x Regression Variant) for each metric
  2. Summary CSV table for direct comparison
"""

import argparse
import csv
import os
import re

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

METRICS_TO_PLOT = [
    ("rmse_overall_mm", "Total Position RMSE [mm]"),
    ("max_pos_error_mm", "Max Position Error [mm]"),
    ("endpoint_pos_error_mm", "Final Position Error [mm]"),
    ("mean_angular_error_deg", "Mean Angular Error [deg]"),
    ("max_angular_error_deg", "Max Angular Error [deg]"),
    ("endpoint_orient_error_deg", "Final Angular Error [deg]"),
]

# Expected trial format: real_traj<ID>_<variant> (e.g., real_trajA_lwr, real_trajB_ridge)
TRIAL_RE = re.compile(r"^real_(traj[A-Z0-9]+)_(.+)$")


def parse_trial(trial_str):
    m = TRIAL_RE.match(trial_str)
    if not m:
        return None, None
    return m.group(1), m.group(2)


def load_summary(path):
    rows = []
    with open(path) as f:
        reader = csv.DictReader(f)
        for row in reader:
            traj_id, variant = parse_trial(row["trial"])
            if traj_id is None:
                # Fallback parsing if trial format differs (e.g. trajA_lwr)
                parts = row["trial"].split("_")
                if len(parts) >= 2:
                    traj_id = parts[0]
                    variant = "_".join(parts[1:])
                else:
                    continue
            row["_traj_id"] = traj_id
            row["_variant"] = variant
            rows.append(row)
    return rows


def plot_grouped_bar(rows, metric_key, metric_label, plot_dir):
    trajectories = sorted(list(set(r["_traj_id"] for r in rows)))
    variants = sorted(list(set(r["_variant"] for r in rows)))

    if not trajectories or not variants:
        return None

    # Map: traj -> variant -> val
    data_map = {}
    for r in rows:
        t_id = r["_traj_id"]
        v_id = r["_variant"]
        val = float(r[metric_key])
        data_map.setdefault(t_id, {})[v_id] = val

    x = np.arange(len(trajectories))
    width = 0.35 if len(variants) == 2 else 0.8 / len(variants)

    fig, ax = plt.subplots(figsize=(9, 5.5))
    colors = ["tab:blue", "tab:orange", "tab:green", "tab:purple", "tab:red"]

    for i, var_name in enumerate(variants):
        vals = [data_map.get(t_id, {}).get(var_name, 0.0) for t_id in trajectories]
        offset = (i - (len(variants) - 1) / 2) * width
        rects = ax.bar(x + offset, vals, width, label=var_name, color=colors[i % len(colors)], alpha=0.85)

        # Add value labels above bars
        for rect in rects:
            height = rect.get_height()
            ax.annotate(f"{height:.3f}",
                        xy=(rect.get_x() + rect.get_width() / 2, height),
                        xytext=(0, 3),  # 3 points vertical offset
                        textcoords="offset points",
                        ha="center", va="bottom", fontsize=8)

    ax.set_xlabel("Real Trajectory")
    ax.set_ylabel(metric_label)
    ax.set_title(f"{metric_label} Comparison by Real Trajectory and Method")
    ax.set_xticks(x)
    ax.set_xticklabels(trajectories)
    ax.legend(title="Variant")
    ax.grid(axis="y", alpha=0.3)
    fig.tight_layout()

    out_path = os.path.join(plot_dir, f"real_traj_comp_{metric_key}.png")
    fig.savefig(out_path, dpi=150)
    plt.close(fig)
    return out_path


def write_comparison_table(rows, plot_dir):
    trajectories = sorted(list(set(r["_traj_id"] for r in rows)))
    variants = sorted(list(set(r["_variant"] for r in rows)))

    out_path = os.path.join(plot_dir, "real_trajectories_comparison_table.csv")
    metric_keys = [k for k, _ in METRICS_TO_PLOT]

    with open(out_path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["trajectory", "variant"] + metric_keys)
        for t_id in trajectories:
            for v_id in variants:
                match = [r for r in rows if r["_traj_id"] == t_id and r["_variant"] == v_id]
                if match:
                    r = match[0]
                    writer.writerow([t_id, v_id] + [r[k] for k in metric_keys])
    return out_path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--summary-csv", required=True, help="Summary CSV produced by the sweep")
    parser.add_argument("--plot-dir", default="plots/02_real_data", help="Output directory for plots")
    args = parser.parse_args()

    rows = load_summary(args.summary_csv)
    if not rows:
        print("No valid rows found in summary CSV.")
        return

    os.makedirs(args.plot_dir, exist_ok=True)

    print("\n== Generating comparative plots for real trajectories ==")
    for metric_key, metric_label in METRICS_TO_PLOT:
        out_p = plot_grouped_bar(rows, metric_key, metric_label, args.plot_dir)
        if out_p:
            print(f"  Plot saved: {out_p}")

    tbl_p = write_comparison_table(rows, args.plot_dir)
    print(f"\nSummary table saved: {tbl_p}")


if __name__ == "__main__":
    main()

